/**
 * Тесты поиска по справочнику вузов (уточнение У31).
 *
 * Проверяется не «нашлось хоть что-то», а порядок: при коротком запросе
 * совпадает половина справочника, и ценность поиска целиком в том, что
 * оказалось первым.
 */
import { describe, expect, it } from 'vitest';

import { fromLatinLayout, normalise, searchUniversities } from './universitySearch';

const CATALOGUE = [
  { short_name: 'МГУ', name: 'Московский государственный университет', city: 'Москва' },
  {
    short_name: 'СПбГУ',
    name: 'Санкт-Петербургский государственный университет',
    city: 'Санкт-Петербург',
  },
  { short_name: 'ДВФУ', name: 'Дальневосточный федеральный университет', city: 'Владивосток' },
  {
    short_name: 'СПбПУ',
    name: 'Санкт-Петербургский политехнический университет',
    city: 'Санкт-Петербург',
  },
];

const names = (query: string): string[] =>
  searchUniversities(CATALOGUE, query).map((item) => item.short_name);

describe('поиск вуза', () => {
  it('пустой запрос отдаёт весь справочник в исходном порядке', () => {
    // Шторка обязана показать варианты сразу, ещё до первого символа.
    expect(names('')).toEqual(['МГУ', 'СПбГУ', 'ДВФУ', 'СПбПУ']);
  });

  it('совпадение в аббревиатуре идёт раньше совпадения в городе', () => {
    // «м» есть и в МГУ, и в слове «Москва», и внутри других названий.
    expect(names('м')[0]).toBe('МГУ');
  });

  it('находит по началу слова в полном названии', () => {
    expect(names('политех')).toEqual(['СПбПУ']);
  });

  it('находит по городу, когда название ни при чём', () => {
    expect(names('владивосток')).toEqual(['ДВФУ']);
  });

  it('сужает выдачу с каждым следующим символом', () => {
    const step1 = names('с');
    const step2 = names('спб');
    const step3 = names('спбп');

    expect(step1.length).toBeGreaterThan(step2.length);
    expect(step2).toEqual(['СПбГУ', 'СПбПУ']);
    expect(step3).toEqual(['СПбПУ']);
  });

  it('не различает ё и е', () => {
    expect(normalise('Королёв')).toBe(normalise('королев'));
  });

  it('понимает забытую раскладку', () => {
    // «vue,» на латинской клавиатуре — это «мгу» на русской.
    expect(fromLatinLayout('vue')).toBe('мгу');
    expect(names('vue')).toEqual(['МГУ']);
  });

  it('на бессмысленный запрос отдаёт пусто, а не весь справочник', () => {
    // Пустой результат честнее: экран покажет подсказку, а не список наугад.
    expect(names('щщщщщ')).toEqual([]);
  });
});
