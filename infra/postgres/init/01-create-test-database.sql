-- Создаёт отдельную базу для интеграционных тестов.
--
-- Тех. ТЗ 7 запрещает гонять интеграционные тесты на общей dev-базе, поэтому
-- рядом с рабочей базой поднимается `<POSTGRES_DB>_test`.
--
-- Выполняется только при первой инициализации кластера, то есть когда том
-- postgres-data пустой. После `docker compose down -v` — выполнится снова.
--
-- Почему SQL, а не shell (решение Р63): shell-скрипт entrypoint выполняет
-- через шебанг, и на Windows с `core.autocrlf=true` файл приезжает с CRLF,
-- шебанг превращается в `#!/bin/sh\r`, а контейнер падает с кодом 126. У .sql
-- интерпретатора нет: его читает psql, для которого `\r` — обычный пробел.
--
-- `:DBNAME` и `:USER` — встроенные переменные psql: имя базы и пользователя
-- текущего подключения. Entrypoint подключается как `$POSTGRES_USER` к
-- `$POSTGRES_DB`, поэтому имя тестовой базы выводится из них и остаётся верным,
-- даже если базу переименовали в `.env`.
--
-- `\gexec` нужен потому, что имя базы в CREATE DATABASE нельзя передать
-- параметром: запрос сначала собирает текст команды, затем psql его выполняет.
-- `format(%I)` экранирует идентификаторы.
SELECT format('CREATE DATABASE %I OWNER %I', :'DBNAME' || '_test', :'USER')
\gexec

-- Без подстановки имени: `:DBNAME_test` psql прочитал бы как имя переменной
-- целиком (подчёркивание в именах допустимо) и напечатал бы её как есть.
\echo база для интеграционных тестов создана
